/**
 * Create an icon to put in front of a button's text.
 * @param {string} name a key of ICONS
 * @returns {SVGSVGElement}
 */
export function icon(name) {
  const svg = svgElement("svg", { class: "icon", viewBox: "0 0 24 24", "aria-hidden": "true" });
  for (const [tag, attributes] of ICONS[name]) svg.append(svgElement(tag, attributes));
  return svg;
}

function svgElement(tag, attributes) {
  const node = document.createElementNS(SVG_NS, tag);
  for (const [name, value] of Object.entries(attributes)) node.setAttribute(name, value);
  return node;
}
